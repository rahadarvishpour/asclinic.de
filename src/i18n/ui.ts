export const DEFAULT_LOCALE: Locale = "en";

export function localePath(locale: Locale, path = "") {
  const base = locale === DEFAULT_LOCALE ? "" : `/${locale}`;
  return `${base}${path}` || "/";
}

const NON_DEFAULT_CODES = LOCALES.map((l) => l.code).filter((c) => c !== DEFAULT_LOCALE);

/** Strips a locale prefix (e.g. "/de/treatments/x" -> "/treatments/x", "/de" -> "/") so the
 *  remainder can be re-prefixed for another locale via localePath(). Paths with no locale
 *  prefix (the default-locale/English paths) are returned unchanged. */
export function stripLocalePrefix(pathname: string): string {
  for (const code of NON_DEFAULT_CODES) {
    if (pathname === `/${code}`) return "/";
    if (pathname.startsWith(`/${code}/`)) return pathname.slice(code.length + 1) || "/";
  }
  return pathname || "/";
}

/** Given the CURRENT pathname (any locale) and a target locale, returns the equivalent path
 *  in that locale — same page, different locale prefix — instead of always the homepage. */
export function localizedPathFor(currentPathname: string, target: Locale): string {
  const stripped = stripLocalePrefix(currentPathname);
  return localePath(target, stripped === "/" ? "" : stripped);
}

/** Link to a homepage section (#book, #faq, …) from anywhere on the site.
 *
 *  On the homepage this is a bare fragment so the browser scrolls in place. On
 *  any other page it must carry the homepage path, otherwise the link points at
 *  an id that does not exist on the current page and silently does nothing.
 *  Note `localePath` returns "/" for the default locale, so the path cannot be
 *  omitted just because it looks empty. */
export function sectionHref(locale: Locale, pathname: string, id: string): string {
  const onHomepage = stripLocalePrefix(pathname) === "/";
  return onHomepage ? `#${id}` : `${localePath(locale)}#${id}`;
}

/** External booking system. Every "Book a visit" / "Book a consultation" CTA on the
 *  site points here rather than at an on-page form, and carries the visitor's current
 *  language so the booking flow opens already translated. */
const BOOKING_BASE = "http://167.235.57.177:3200/c/defaultcomp1/book/defaultcomp1";

export function bookingUrl(locale: Locale): string {
  return `${BOOKING_BASE}?lang=${locale}`;
}

export function getLocaleMeta(locale: Locale): LocaleMeta {
  return LOCALES.find((l) => l.code === locale) ?? LOCALES[0];
}

